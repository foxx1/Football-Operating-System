const I18nContext = createContext<I18nContextType | undefined>(undefined);

const interpolate = (value: string, params?: Record<string, string>) => {
  if (!params) return value;
  return Object.entries(params).reduce(
    (text, [key, paramValue]) => text.replaceAll(`{${key}}`, paramValue),
    value,
  );
};

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const saved = localStorage.getItem("app-locale");
    return saved === "ar" ? "ar" : "en";
  });

  const direction = locale === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    document.documentElement.lang = locale === "ar" ? "ar-BH" : "en";
    document.documentElement.dir = direction;
    document.documentElement.dataset.locale = locale;
  }, [direction, locale]);

  const value = useMemo<I18nContextType>(() => {
    const setLocale = (nextLocale: Locale) => {
      localStorage.setItem("app-locale", nextLocale);
      setLocaleState(nextLocale);
    };

    return {
      locale,
      direction,
      isRtl: direction === "rtl",
      setLocale,
      toggleLocale: () => setLocale(locale === "ar" ? "en" : "ar"),
      t: (key: string) => translations[locale][key] ?? translations.en[key] ?? key,
    };
  }, [direction, locale]);

  return (
    <I18nContext.Provider value={value}>
      {/* Radix primitives (Select, DropdownMenu, etc.) default to ltr
          internally and never look at the document's dir attribute on
          their own — without this, every Radix-based dropdown mirrors
          incorrectly in RTL regardless of the page around it. */}
      <DirectionProvider dir={direction}>{children}</DirectionProvider>
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used within an I18nProvider");
  }
  return context;
}

export function translateWithParams(t: (key: string) => string, key: string, params: Record<string, string>) {
  return interpolate(t(key), params);
}
